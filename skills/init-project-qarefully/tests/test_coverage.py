    def test_accepted_merge_retains_each_reason(self):
        self.dirs("payments", "promos")
        proposed = ("## Container: .\n## Scope: payments\n- path: payments -> Payment source\n"
                    "## Scope: promos\n- path: promos -> Promo source\n")
        accepted = ("## Scope: commerce\n- path: payments -> Shared checkout boundary\n"
                    "- path: promos -> Shared promo guards\n## Mappings\npayments + promos -> commerce\n")
        self.check(proposed, accepted=accepted)
        report = self.report()
        self.assertEqual(report["counts"]["accepted_scopes"], 1)
        self.assertEqual([r["reason"] for r in report["assignments"]["accepted"]],
                         ["Shared checkout boundary", "Shared promo guards"])
        for field, path in (("proposal_sha256", self.proposal), ("accepted_sha256", self.accepted)):
            with open(path, "rb") as handle:
                self.assertEqual(report[field], hashlib.sha256(handle.read()).hexdigest())

