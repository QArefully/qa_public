    def test_unreadable_directory_errors_and_cleans_guarded_output(self):
        self.dirs("blocked")
        self.proposal_text("## Container: .\n## Container: blocked\n")
        self.write("attempts/scan-1/coverage.json", "STALE", base=self.run_dir)
        ledger = load_script("ledger")
        scandir = ledger.os.scandir

        def denied(path):
            if ledger.key(ledger.common.unfs(path)) == ledger.key(os.path.join(self.root, "blocked")):
                raise PermissionError("private permission detail")
            return scandir(path)
        with mock.patch.object(ledger.os, "scandir", side_effect=denied), contextlib.redirect_stderr(io.StringIO()):
            code = ledger.main(["coverage", self.run_dir, self.proposal, "--out", self.out])
        self.assertEqual(code, 2)
        self.assertFalse(os.path.exists(self.out))

