class Coverage(RepoCase):
    def setUp(self):
        super().setUp()
        self.run_dir = os.path.join(self.root, "run")
        self.assertEqual(run("ledger.py", "baseline", self.root, self.run_dir)[0], 0)
        self.proposal = os.path.join(self.run_dir, "scope-proposal.md")
        self.accepted = os.path.join(self.run_dir, "accepted-scopes.md")
        self.out = os.path.join(self.run_dir, "attempts", "scan-1", "coverage.json")

    def dirs(self, *paths):
        for path in paths:
            os.makedirs(os.path.join(self.root, *path.split("/")), exist_ok=True)

    def proposal_text(self, text):
        return self.write("scope-proposal.md", text, base=self.run_dir)

    def check(self, text=None, accepted=None, out=None, expected=0):
        if text is not None:
            self.proposal_text(text)
        args = ["coverage", self.run_dir, self.proposal]
        if accepted is not None:
            self.write("accepted-scopes.md", accepted, base=self.run_dir)
            args += ["--accepted", self.accepted]
        result = run("ledger.py", *args, "--out", out or self.out)
        self.assertEqual(result[0], expected, result)
        return result

    def report(self):
        with open(self.out, encoding="utf-8") as handle:
            return json.load(handle)

    def domain(self):
        self.dirs(*(f"apps/api/src/features/{p}" for p in
                    ("payments", "promos", "invoices", "audit", "catalog", "customBlend")))
        return ("## Container: .\n## Container: apps\n## Container: apps/api\n"
                "## Container: apps/api/src\n## Container: apps/api/src/features\n"
                "## Scope: commerce\n- path: apps/api -> API boundary\n"
                "- path: apps/api/src/features/payments -> SECRET-PAYMENT-REASON\n"
                "- path: apps/api/src/features/promos -> Merge promo guards\n")

    def test_missing_feature_children_despite_ancestor_scope(self):
        text = self.domain()
        _, stdout, _ = self.check(text, expected=1)
        report = self.report()
        self.assertEqual(report["uncovered"], [f"apps/api/src/features/{p}" for p in
                                              ("audit", "catalog", "customBlend", "invoices")])
        self.assertEqual({i["code"] for i in report["issues"]}, {"unclassified"})
        self.assertNotIn("SECRET-PAYMENT-REASON", "\n".join(stdout))
        self.assertNotIn("invoices", "\n".join(stdout))
        self.assertEqual(report["assignments"]["proposal"][1]["reason"], "SECRET-PAYMENT-REASON")

    def test_explicit_merged_paths_and_skips_pass(self):
        text = self.domain()
        text += "- path: apps/api/src/features/invoices -> Shared payment evidence\n"
        text += "- path: apps/api/src/features/audit -> Shared audit investigation\n"
        text += "## Skipped: apps/api/src/features/catalog -> Data-only consumed by API configuration\n"
        text += "## Skipped: apps/api/src/features/customBlend -> Generated by schema/build.py\n"
        self.check(text)
        self.assertEqual(self.report()["counts"]["proposed_scopes"], 1)
        self.assertEqual(self.report()["counts"]["skipped"], 2)

